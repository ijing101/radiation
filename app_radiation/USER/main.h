/* ============================================================================
 * Modbus 保持寄存器地址映射表（从机视角，上位机用 0x03 读、0x06写）
 * ----------------------------------------------------------------------------
 * Reg[0]  辐射整型值        		（只读）标定并限幅后的辐照度，范围 0~2000 W/m²,取四舍五入
 * Reg[1]  辐射浮点值 高16位 		（只读）IEEE754 F32，单位 W/m²（MS-80SH 字序）
 * Reg[2]  辐射浮点值 低16位 		（只读）与 Reg[1] 组成 float；高字在前（大端）
 * Reg[3]  辐射校准基准值 高16位 （只读）IEEE754 F32；写入灵敏度前的中间值，高字在前
 * Reg[4]  辐射校准基准值 低16位 （只读）与 Reg[3] 组成 float
 
 * Reg[15] 版本号								 (只读) 60062 
 
 * Reg[17] IAP 升级触发  0x11    （可写）写入 0x1234 触发进入 Bootloader 升级
 
 * Reg[20] 校准系数 		  0x14      （读写）20000~40000，写后存 EEPROM
 * Reg[21] 辐射灵敏度   0x15      （读写）5.000~15.000 µV/(W/m²) 的 ×1000 值，即 5000~15000
 * Reg[22]
 * Reg[23]  从机地址    0x17     （读写）1~99，写后保存并复位生效
 * Reg[24]  波特率      0x18     （读写）0=9600，1=19200,2=115200，写后保存并复位生效

 * ==========================================================================*/

/* Modbus 寄存器地址定义（标定参数，与上表对应） */
#define REG_PARAM_DIR    20   /* 校准系数：20000~40000 */
#define REG_PARAM_RADI   21   /* 灵敏度 ×1000：5000~15000 */


#endif /* __MAIN_H */
